def _tgws_dd(s):
    try:
        s = str(s or "")
        if s[-4:] != ".com":
            return s
        prefix = s[:-4]
        n = sum(1 for c in prefix if c.isalpha())
        out = []
        for c in prefix:
            if c.isalpha():
                base = 97 if c > "`" else 65
                out.append(chr((ord(c) - base - n) % 26 + base))
            else:
                out.append(c)
        return "".join(out) + _TGWS_CFPROXY_SUFFIX
    except:
        return str(s or "")


def _tgws_is_valid_domain(domain):
    try:
        domain = str(domain or "")
        if not domain or len(domain) > 253:
            return False
        if domain.startswith(".") or domain.endswith("."):
            return False
        labels = domain.split(".")
        if len(labels) < 2:
            return False
        for label in labels:
            if not label or len(label) > 63:
                return False
            if label[0] == "-" or label[-1] == "-":
                return False
            if not all(ch.isalnum() or ch == "-" for ch in label):
                return False
        tld = labels[-1]
        if len(tld) < 2 or not any(ch.isalpha() for ch in tld):
            return False
        return True
    except:
        return False


def _tgws_normalize_domain_pool(domains):
    seen = set()
    normalized = []
    try:
        for domain in list(domains or []):
            item = str(domain or "").strip().lower()
            if not _tgws_is_valid_domain(item):
                continue
            if item in seen:
                continue
            seen.add(item)
            normalized.append(item)
    except:
        pass
    return normalized


